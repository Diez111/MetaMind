//! Box-model snapshots of formulas taken from the vault this crate serves (Analisis Matematico I),
//! plus one row per feature the box model is judged on. The dump is the contract with the painter:
//! if a number moves, it moves on purpose and the test says by how much.

use super::*;

fn lay(src: &str, display: bool) -> Layout {
    render(src, 16.0, display, &mut Approx)
}

fn face(f: Face) -> char {
    match f {
        Face::Roman => 'R',
        Face::Italic => 'I',
        Face::Bold => 'B',
        Face::Mono => 'M',
    }
}

fn hex(c: Option<Color>) -> String {
    match c {
        Some(c) => format!("#{:02x}{:02x}{:02x}", c.r, c.g, c.b),
        None => "-".to_string(),
    }
}

/// One line per glyph and per segment, rounded to a hundredth of a pixel. `w/a/d` is the padded box,
/// `g x y size face color text` a glyph by its baseline, `s x0 y0 x1 y1 width color` a segment.
fn dump(l: &Layout) -> String {
    let mut s = format!("box w={:.2} a={:.2} d={:.2}", l.width, l.ascent, l.descent);
    for g in &l.glyphs {
        let line = format!(
            "g {:.2} {:.2} {:.2} {} {} {}",
            g.x,
            g.y,
            g.size,
            face(g.face),
            hex(g.color),
            g.text.escape_debug()
        );
        s = s + "\n" + &line;
    }
    for sg in &l.segs {
        let line = format!(
            "s {:.2} {:.2} {:.2} {:.2} {:.2} {}",
            sg.x0,
            sg.y0,
            sg.x1,
            sg.y1,
            sg.width,
            hex(sg.color)
        );
        s = s + "\n" + &line;
    }
    // The tag is not part of the formula box: it is reported so the caller can hit the right margin.
    if let Some(t) = &l.tag {
        let line = format!("tag {} star={} x={:.2} y={:.2} w={:.2}", t.label(), t.star, t.x, t.y, t.width);
        s = s + "\n" + &line;
    }
    s
}

