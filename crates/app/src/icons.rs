use metamind_ui::{Cmd, Dom, El};

type Line = Vec<(f32, f32)>;

/// Lucide's box, in icon units. Coordinates below are read straight off the SVG.
const GRID: f32 = 24.0;
/// Lucide's `stroke-width`, in icon units: a 16 px icon is stroked at 1.33 px.
const STROKE: f32 = 2.0;

#[derive(Default)]
struct Shape {
    lines: Vec<Line>,
    dots: Vec<[f32; 3]>,
}

impl Shape {
    /// Start a subpath at `(x, y)` (SVG `M`).
    fn m(mut self, x: f32, y: f32) -> Shape {
        self.lines.push(vec![(x, y)]);
        self
    }
    /// A straight segment to `(x, y)` (SVG `L`, `H`, `V`).
    fn l(mut self, x: f32, y: f32) -> Shape {
        match self.lines.last_mut() {
            Some(line) => line.push((x, y)),
            None => self.lines.push(vec![(x, y)]),
        }
        self
    }
    /// A cubic Bézier from the current point (SVG `C`, and `Q`/`S`/`T`/`A` once converted),
    /// flattened here so the painter still only ever sees polylines.
    fn c(mut self, x1: f32, y1: f32, x2: f32, y2: f32, x: f32, y: f32) -> Shape {
        let (x0, y0) = self.lines.last().and_then(|l| l.last().copied()).unwrap_or((x1, y1));
        let hull = (x1 - x0).hypot(y1 - y0) + (x2 - x1).hypot(y2 - y1) + (x - x2).hypot(y - y2);
        let n = ((hull / 1.2).ceil() as usize).clamp(4, 24);
        let pts = (1..=n)
            .map(|i| {
                let t = i as f32 / n as f32;
                let u = 1.0 - t;
                (
                    u * u * u * x0 + 3.0 * u * u * t * x1 + 3.0 * u * t * t * x2 + t * t * t * x,
                    u * u * u * y0 + 3.0 * u * u * t * y1 + 3.0 * u * t * t * y2 + t * t * t * y,
                )
            })
            .collect::<Vec<_>>();
        match self.lines.last_mut() {
            Some(line) => line.extend(pts),
            None => self.lines.push(pts),
        }
        self
    }
    /// Close the subpath back to where it started (SVG `Z`).
    fn z(mut self) -> Shape {
        if let Some(line) = self.lines.last_mut() {
            if let Some(&first) = line.first() {
                line.push(first);
            }
        }
        self
    }
    fn dot(mut self, x: f32, y: f32, r: f32) -> Shape {
        self.dots.push([x, y, r]);
        self
    }
    /// A sharp square, for a name no icon is drawn for.
    fn rect(self, x0: f32, y0: f32, x1: f32, y1: f32) -> Shape {
        self.m(x0, y0).l(x1, y0).l(x1, y1).l(x0, y1).z()
    }
}

